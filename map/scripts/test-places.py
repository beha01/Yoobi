#!/usr/bin/env python3
"""Проверка адресов по-русски (scripts/places.py) без выгрузки OSM."""

import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
from places import StreetIndex, address_names, house_number  # noqa: E402

failed = 0


def check(name, cond):
    global failed
    print(('✓ ' if cond else '✗ ') + name)
    failed += not cond


xy = lambda lon, lat: (lon * 87000, lat * 110540)  # noqa: E731 — плоскость в метрах
G = ('кӯчаи Гафуров', 'улица Гафурова', '', 'B. Ghafurov Street')
BG = ('кӯчаи Бобоҷон Гафуров', 'улица Бабаджана Гафурова', '', 'B. Ghafurov Street')
streets = [  # точки участков: середина и концы
    (68.7390, 38.5700, G), (68.7400, 38.5704, G),
    (68.7401, 38.5704, BG), (68.7402, 38.5705, BG), (68.7430, 38.5712, BG),  # продолжение улицы
    (68.7399, 38.5703, ('кӯчаи Бобоҷон Ғафуров', 'улица Бободжона Гафурова', '', '')),  # другое написание
    (68.7460, 38.5730, ('кӯчаи Бобоҷон Ғафуров 1-у гуз', 'улица Бободжона Гафурова 1-й пр.', '', '')),
    (68.9000, 38.6500, ('кӯчаи Хуҷандӣ', 'улица Худжанди', '', '')),
    (68.9200, 38.6500, ('кӯчаи Муродии Хуҷандӣ', 'улица Муроди Худжанди', '', '')),  # другая улица в 1,7 км
    (68.7800, 38.5800, ('хиёбони Рӯдакӣ', 'проспект Рудаки', '', 'Rudaki Avenue')),
    (68.8000, 38.5900, ('кӯчаи Фирдавсӣ', 'улица Фирдоуси', '', '')),
    (68.8010, 38.5905, ('кӯчаи К. Фирдавсӣ', 'улица К. Фирдавси', '', '')),        # инициал — не имя
    (68.8100, 38.5950, ('кӯчаи Ваҳдат', 'улица Вахдат', '', '')),
    (68.8105, 38.5955, ('кӯчаи Равзана (Ваҳдат)', 'улица Равзана (Вахдат)', '', '')),  # другая улица
    (68.8200, 38.6000, ('кӯчаи Хуҷандӣ', 'улица Худжанди', '', '')),
    (68.8205, 38.6005, ('хиёбони Камоли Хуҷандӣ', 'проспект Камоли Худжанди', '', '')),  # другой тип
]
index = StreetIndex(streets, xy)
found = index.find('Кӯчаи Гафуров', 68.7393, 38.5697)
ru, tg, _en = address_names('Кӯчаи Гафуров', '46/2', found)
check('полное имя улицы, как в 2ГИС, самым частым написанием', ru == 'улица Бабаджана Гафурова, 46/2')
check('таджикское написание', tg == 'кӯчаи Бобоҷон Гафуров, 46/2')
check('проезд не подменяет улицу', 'пр.' not in ru)
far = index.find('Кӯчаи Гафуров', 68.7000, 38.5500)
check('далёкая улица с полным именем не подставляется', far is None or far[1] == 'улица Гафурова')
ru, _tg, _en = address_names('хиёбони Рӯдакӣ', '10', index.find('хиёбони Рӯдакӣ', 68.7801, 38.5801))
check('проспект остаётся проспектом', ru == 'проспект Рудаки, 10')
for street, at, expect in (('кӯчаи Хуҷандӣ', (68.9001, 38.6501), 'улица Худжанди, 1'),
                           ('кӯчаи Фирдавсӣ', (68.8001, 38.5901), 'улица Фирдоуси, 1'),
                           ('кӯчаи Ваҳдат', (68.8101, 38.5951), 'улица Вахдат, 1'),
                           ('кӯчаи Хуҷандӣ', (68.8201, 38.6001), 'улица Худжанди, 1')):
    ru, _tg, _en = address_names(street, '1', index.find(street, *at))
    check(f'не подменяется: {expect}', ru == expect)
# Участки одной улицы подписаны по-разному: у всех домов — самое частое написание.
R1 = ('кӯчаи А. Расулов', 'улица А. Расулова', '', '')
R2 = ('кӯчаи А. Расулов', 'улица А.Расулов', '', '')
index2 = StreetIndex([(69.0000, 39.0000, R2), (69.0010, 39.0002, R1), (69.0020, 39.0004, R1),
                      (69.0030, 39.0006, R1)], xy)
ru, _tg, _en = address_names('кӯчаи А. Расулов', '7', index2.find('кӯчаи А. Расулов', 69.0001, 39.0001))
check('одно написание улицы у всех домов', ru == 'улица А. Расулова, 7')
J1 = ('кӯчаи Ҷӯра Зокиров', 'улица Джура Закиров', '', '')
J2 = ('кӯчаи Ҷӯра Зокиров', 'улица Чура Зокир', '', '')
D1 = ('кӯчаи Аҳмади Дониш', 'улица Ахмада Дониша', '', '')
D2 = ('кӯчаи Аҳмади Дониш', 'улица Ахмади Дониш', '', '')
index3 = StreetIndex([(70.0, 40.0, J2), (70.001, 40.0, J2), (70.002, 40.0, J2), (70.003, 40.0, J1),
                      (71.0, 40.0, D2), (71.001, 40.0, D2), (71.002, 40.0, D2), (71.003, 40.0, D1)], xy)
ru, _tg, _en = address_names('кӯчаи Ҷӯра Зокиров', '3', index3.find('кӯчаи Ҷӯра Зокиров', 70.0005, 40.0))
check('«Джура», а не «Чура», даже если «Чура» чаще', ru == 'улица Джура Закиров, 3')
ru, _tg, _en = address_names('кӯчаи Аҳмади Дониш', '3', index3.find('кӯчаи Аҳмади Дониш', 71.0005, 40.0))
check('фамилия в родительном падеже', ru == 'улица Ахмада Дониша, 3')
index4 = StreetIndex([(72.0, 40.0, ('кӯчаи Горкий', 'улица Горького', '', '')),
                      (72.001, 40.0, ('кӯчаи Горкий', 'улица Горкий', '', '')),
                      (72.002, 40.0, ('кӯчаи Горкий', 'улица Горкий', '', '')),
                      (72.1, 40.0, ('кӯчаи Сирдарё', 'улица Сырдарья', '', '')),
                      (72.2, 40.0, ('кучаи Д.Холматов', None, '', '')), (72.201, 40.0, ('кучаи Д.Холматов', None, '', '')),
                      (72.202, 40.0, ('кучаи Д,Холматов', 'улица Д,Холматов', '', ''))], xy)
for street, at, expect in (('кӯчаи Горкий', (72.0011, 40.0), 'улица Горького, 5'),
                           ('кӯчаи Сирдарё', (72.1001, 40.0), 'улица Сырдарья, 5'),
                           ('кучаи Д,Холматов', (72.2021, 40.0), 'улица Д.Холматов, 5')):
    ru, _tg, _en = address_names(street, '5', index4.find(street, *at))
    check(f'лучшее русское написание: {expect}', ru == expect)
T1 = ('кӯчаи Мирзо Турсунзода', 'улица Мирзо Турсунзаде', '', '')
T2 = ('кӯчаи Мирзо Турсунзода', None, '', '')
index5 = StreetIndex([(73.0, 40.0, T2), (73.001, 40.0, T2), (73.002, 40.0, T1)], xy)
ru, _tg, _en = address_names('кӯчаи Мирзо Турсунзода', '8', index5.find('кӯчаи Мирзо Турсунзода', 73.0001, 40.0))
check('русское имя из OSM лучше переложения', ru == 'улица Мирзо Турсунзаде, 8')
check('номер с дробью', house_number('32\\1') == '32/1' and house_number('5 а') == '5а')

print('\nАдреса в порядке' if not failed else f'\nОшибок: {failed}')
sys.exit(1 if failed else 0)
